fun decodedDartDefines(): Map<String, String> {
    val raw = (project.findProperty("dart-defines") as String?).orEmpty()
    if (raw.isBlank()) return emptyMap()
    return raw.split(",").mapNotNull { entry ->
        val decoded = runCatching {
            String(Base64.getDecoder().decode(entry.trim()), Charsets.UTF_8)
        }.getOrNull() ?: return@mapNotNull null
        val separator = decoded.indexOf('=')
        if (separator <= 0) return@mapNotNull null
        decoded.substring(0, separator) to decoded.substring(separator + 1)
    }.toMap()
}

// Fail fast for release builds when required secure material is missing, so the
// project can never produce a falsely "release" AAB signed with debug
// credentials or shipping the placeholder Mapbox token.
gradle.taskGraph.whenReady {
    val buildingRelease = allTasks.any { task ->
        val name = task.name
        name.contains("Release") &&
            (name.startsWith("assemble") || name.startsWith("bundle") || name.startsWith("package"))
    }
    val compilingDart = allTasks.any { task ->
        task.name.startsWith("compileFlutter")
    }
    val runtimeEnv = decodedDartDefines()["FLUXIDI_RUNTIME_ENV"]
        ?.trim()
        ?.lowercase()
        .orEmpty()
    if (fluxidiStaging && compilingDart && runtimeEnv != "staging") {
        throw GradleException(
            "Staging package requires --dart-define=FLUXIDI_RUNTIME_ENV=staging",
        )
    }
    if (!fluxidiStaging && !fluxidiE2e && runtimeEnv == "staging") {
        throw GradleException(
            "FLUXIDI_RUNTIME_ENV=staging requires -PfluxidiStaging=true",
        )
    }
    if (fluxidiDeviceQa && buildingRelease) {
        throw GradleException("Device QA identity is debug-only and cannot create a release bundle")
    }
    if (buildingRelease) {
        if (fluxidiE2e || fluxidiStaging) {
            val fullId =
                (android.defaultConfig.applicationId ?: "") +
                    (android.defaultConfig.applicationIdSuffix ?: "")
            val expectedId = if (fluxidiStaging) {
                "com.fluxidi.tracking.staging"
            } else {
                "com.fluxidi.tracking.e2e"
            }
            if (fullId != expectedId) {
                throw GradleException(
                    "Release package must be $expectedId, was $fullId",
                )
            }
        }
        if (!hasReleaseKeystore) {
            throw GradleException(
                "RELEASE_KEYSTORE_CREATION_REQUIRED: android/key.properties not found. " +
                    "A release build must be signed with a dedicated upload keystore. " +
                    "Create the keystore and android/key.properties (storeFile, storePassword, keyAlias, keyPassword). " +
                    "Debug signing is not permitted for release builds.",
            )
        }

    }
}

