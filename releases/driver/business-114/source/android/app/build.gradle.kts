// Match plugin compilation to the existing app SDK. This changes neither
// targetSdk/minSdk nor runtime permissions; old plugins otherwise fail AAR checks.
val fluxidiAppCompileSdk = flutter.compileSdkVersion
rootProject.subprojects {
    afterEvaluate {
        extensions.findByType(com.android.build.gradle.BaseExtension::class.java)?.let { libraryAndroid ->
            val currentSdk = libraryAndroid.compileSdkVersion?.removePrefix("android-")?.toIntOrNull()
            if (currentSdk != null && currentSdk < fluxidiAppCompileSdk) {
                libraryAndroid.compileSdkVersion(fluxidiAppCompileSdk)
            }
        }
    }
}
