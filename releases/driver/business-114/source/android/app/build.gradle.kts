// ---------------------------------------------------------------------------
// Fluxidi release configuration (upload signing; MapLibre has no Mapbox token).
//
// Secrets are NEVER committed. They are read from local, gitignored inputs:
//   - android/key.properties      : release/upload keystore credentials
// Release signing remains mandatory. Maps use the owned HTTPS gateway.
// ---------------------------------------------------------------------------

// Reuse existing upload credentials from outside the isolated checkout.
// No signing material is copied or generated by this configuration.
val externalSigningProperties = System.getenv("FLUXIDI_SIGNING_PROPERTIES_PATH")?.takeIf { it.isNotBlank() }
val keystorePropertiesFile = rootProject.file(externalSigningProperties ?: "key.properties")
val hasReleaseKeystore = keystorePropertiesFile.exists()
val keystoreProperties = Properties()
if (hasReleaseKeystore) {
    keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
    if (externalSigningProperties != null) {
        val location = keystoreProperties.getProperty("storeFile").orEmpty()
        if (location.isNotBlank() && !File(location).isAbsolute) {
            keystoreProperties.setProperty("storeFile",
                File(File(keystorePropertiesFile.parentFile, "app"), location).canonicalPath)
        }
    }

}

