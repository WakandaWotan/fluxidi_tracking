String limousineBusinessSetupProfilePercent(
  double progress,
  AppLanguage language,
) {
  final pct = (progress * 100).round();
  switch (language) {
    case AppLanguage.en:
      return 'Profile $pct% complete';
    case AppLanguage.fr:
      return 'Profil complété à $pct %';
    case AppLanguage.es:
      return 'Perfil $pct % completo';
    case AppLanguage.nl:
    default:
      return 'Profiel $pct% compleet';
  }
}
