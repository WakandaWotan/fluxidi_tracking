LocalizedText limousineBusinessSetupSectionLabel(
  LimousineBusinessSetupSection section,
) {
  switch (section) {
    case LimousineBusinessSetupSection.vehicles:
      return kLimousineBusinessSetupSectionVehicles;
    case LimousineBusinessSetupSection.offers:
      return kLimousineBusinessSetupSectionOffers;
    case LimousineBusinessSetupSection.publicText:
      return kLimousineBusinessSetupSectionPublic;
    case LimousineBusinessSetupSection.review:
      return kLimousineBusinessSetupSectionReview;
  }
}

LocalizedText limousineBusinessSetupChecklistLabel(String code) {
  switch (code) {
    case 'vehicles':
      return kLimousineBusinessSetupCheckVehicles;
    case 'offers':
      return kLimousineBusinessSetupCheckOffers;
    case 'public_text':
      return kLimousineBusinessSetupCheckPublic;
    case 'public_photo':
      return kLimousineBusinessSetupCheckPhoto;
    case 'live_status':
      return kLimousineBusinessSetupTestMessage;
    default:
      return kLimousineBusinessSetupTestNotReadyMessage;
  }
}

LocalizedText limousineBusinessSetupProgressCopy(double progress) {
  if (progress >= 1) return kLimousineBusinessSetupReady;
  if (progress >= 0.34) return kLimousineBusinessSetupAlmostReady;
  return kLimousineBusinessSetupGetStarted;
}

LocalizedText limousineBusinessSetupMissingCopy(
  LimousineBusinessSetupReadiness readiness,
) {
  for (final item in readiness.items) {
    if (item.complete) continue;
    switch (item.code) {
      case 'vehicles':
        return kLimousineBusinessSetupMissingVehicles;
      case 'offers':
        return kLimousineBusinessSetupMissingOffers;
      case 'public_text':
        return kLimousineBusinessSetupMissingText;
      case 'public_photo':
        return kLimousineBusinessSetupMissingPhoto;
      case 'live_status':
        return kLimousineBusinessSetupTestNotReadyMessage;
    }
  }
  return kLimousineBusinessSetupReady;
}

