String limousineCustomerLabel(LocalizedText text, AppLanguage language) =>
    text.of(language);

String limousineCustomerStateLabel(String state, AppLanguage language) {
  final token = LimousineQuoteStateId.normalize(state);
  final label = kLimousineCustomerStateLabels[token];
  if (label == null) return kLimousineQuoteUnknownState.of(language);
  return label.of(language);
}

String limousineCustomerPresentationLabel(
  String presentation,
  AppLanguage language,
) {
  switch (presentation.trim().toLowerCase()) {
    case 'exact_fixed':
    case 'exact':
      return kLimousineCustomerExactPrice.of(language);
    case 'from_price':
    case 'from':
      return kLimousineCustomerFromPrice.of(language);
    case 'indicative':
      return kLimousineCustomerIndicativePrice.of(language);
    case 'quote_required':
      return kLimousineCustomerQuoteRequired.of(language);
    case 'unavailable':
      return kLimousineCustomerUnavailablePrice.of(language);
    default:
      return presentation;
  }
}
