String limousineCustomerLifecycleState(
  String state, {
  LimousineQuoteRequest? request,
}) {
  final token = LimousineQuoteStateId.normalize(
    request?.state.isNotEmpty == true ? request!.state : state,
  );
  if (token == LimousineQuoteStateId.bookingCreated) {
    return LimousineQuoteStateId.bookingCreated;
  }
  if (token == LimousineQuoteStateId.accepted) {
    return LimousineQuoteStateId.accepted;
  }
  if (request?.quotationAvailable == true ||
      token == LimousineQuoteStateId.quoted ||
      token == LimousineQuoteStateId.customerAcceptanceRequired) {
    return LimousineQuoteStateId.quoted;
  }
  if (request?.companyViewed == true ||
      (request?.companyViewedAt ?? '').trim().isNotEmpty ||
      token == LimousineQuoteStateId.viewedByCompany) {
    return LimousineQuoteStateId.viewedByCompany;
  }
  return token;
}

String limousineCustomerViewedByCompanyLabel(
  AppLanguage language, {
  String companyName = '',
}) {
  return kLimousineCustomerCompanyViewedCopy.of(language);
}

String limousineCustomerStateLabel(
  String state,
  AppLanguage language, {
  String companyName = '',
  LimousineQuoteRequest? request,
}) {
  final token = limousineCustomerLifecycleState(state, request: request);
  if (token == LimousineQuoteStateId.viewedByCompany) {
    return limousineCustomerViewedByCompanyLabel(
      language,
      companyName: companyName,
    );
  }
  final label = kLimousineCustomerStateLabels[token];
  if (label == null) return kLimousineQuoteUnknownState.of(language);
  return label.of(language);
}

String limousineCustomerCardStateLabel(
  String state,
  AppLanguage language, {
  String companyName = '',
  LimousineQuoteRequest? request,
}) {
  final token = limousineCustomerLifecycleState(state, request: request);
  if (token == LimousineQuoteStateId.viewedByCompany) {
    return kLimousineCustomerViewedBadge.of(language);
  }
  return limousineCustomerStateLabel(
    token,
    language,
    companyName: companyName,
    request: request,
  );
}

bool limousineCustomerRequestHasBooking(
  String state, {
  LimousineQuoteRequest? request,
}) {
  final token = limousineCustomerLifecycleState(state, request: request);
  return token == LimousineQuoteStateId.accepted ||
      token == LimousineQuoteStateId.bookingCreated;
}

LocalizedText limousineCustomerHideActionLabel({
  required String state,
  LimousineQuoteRequest? request,
}) {
  return limousineCustomerRequestHasBooking(state, request: request)
      ? kLimousineCustomerHideAfterBooking
      : kLimousineCustomerHideFromOverview;
}

String limousineCustomerPresentationLabel(
  String presentation,
  AppLanguage language,
) {
  switch (presentation.trim().toLowerCase()) {
    case 'exact_fixed':
    case 'exact':
      return kLimousineCustomerExactPrice.of(language);
    case 'from_price':
    case 'from':
      return kLimousineCustomerFromPrice.of(language);
    case 'indicative':
      return kLimousineCustomerIndicativePrice.of(language);
    case 'quote_required':
      return kLimousineCustomerQuoteRequired.of(language);
    case 'unavailable':
      return kLimousineCustomerUnavailablePrice.of(language);
    default:
      return presentation;
  }
