String limousineQuoteInboxLabel(LocalizedText text, AppLanguage language) =>
    text.of(language);

String limousineQuoteStateLabel(String state, AppLanguage language) {
  final token = LimousineQuoteStateId.normalize(state);
  final label = kLimousineQuoteStateLabels[token];
  if (label == null) return kLimousineQuoteUnknownState.of(language);
  return label.of(language);
}

String limousineQuoteErrorLabel(
  LimousineQuoteInboxException error,
  AppLanguage language,
) {
  switch (error.kind) {
    case LimousineQuoteInboxErrorKind.session:
      return kLimousineQuoteSessionFailed.of(language);
    case LimousineQuoteInboxErrorKind.gateOff:
      return kLimousineQuoteGateOff.of(language);
    case LimousineQuoteInboxErrorKind.notFound:
      return kLimousineQuoteNotFound.of(language);
    case LimousineQuoteInboxErrorKind.staleRevision:
      return kLimousineQuoteStaleRevision.of(language);
    case LimousineQuoteInboxErrorKind.network:
      return kLimousineQuoteNetworkFailed.of(language);
    case LimousineQuoteInboxErrorKind.invalid:
    case LimousineQuoteInboxErrorKind.unknown:
      return kLimousineQuoteNetworkFailed.of(language);
  }
}
